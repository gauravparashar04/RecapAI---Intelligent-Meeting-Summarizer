/**
 * ===================================================================================
 * FILE: server/src/models/Meeting.js
 * PURPOSE:
 *   Mongoose Schema and Model definition for Meetings.
 * 
 * ROLE IN MERN ARCHITECTURE:
 *   Represents the primary document stored in the MongoDB "meetings" collection.
 *   Unlike Streamlit's temporary memory, this schema persists:
 *     1. Media Source details (URL or filepath, language).
 *     2. Processing Lifecycle status (PROCESSING, COMPLETED, FAILED).
 *     3. Complete extracted intelligence (Title, Executive Summary, Action items,
 *        Key decisions, Open questions, Full transcript).
 *     4. Multi-turn conversational chat history for RAG queries.
 * 
 * INTERVIEW HIGHLIGHT:
 *   Shows data modeling capability in NoSQL databases, schema design for AI
 *   application metadata, and embedding sub-documents (chatHistory) for atomic
 *   retrieval without complex relational joins.
 * ===================================================================================
 */

// Import Mongoose library
const mongoose = require('mongoose');

// Define the sub-schema for individual chat messages in the RAG conversation
const ChatMessageSchema = new mongoose.Schema({
  // Sender role: either the human user or the RAG AI assistant
  sender: {
    type: String,
    enum: ['user', 'assistant'],
    required: [true, 'Message sender role is required'],
  },
  // Text content of the question or the answer
  message: {
    type: String,
    required: [true, 'Message text content cannot be empty'],
  },
  // Timestamp when the message was sent
  timestamp: {
    type: Date,
    default: Date.now,
  },
});

// Define the primary Meeting Schema
const MeetingSchema = new mongoose.Schema(
  {
    // The input source: YouTube URL or local file path
    sourceUrl: {
      type: String,
      required: [true, 'Media source URL or file path is required'],
      trim: true,
    },

    // Selected spoken language mode for transcription
    language: {
      type: String,
      enum: ['english', 'hinglish'],
      default: 'english',
    },

    // Processing lifecycle status of the meeting analysis
    status: {
      type: String,
      enum: ['PENDING', 'PROCESSING', 'COMPLETED', 'FAILED'],
      default: 'PROCESSING',
      index: true, // Indexed for fast status querying and polling
    },

    // Automated meeting session title generated by LLM
    title: {
      type: String,
      default: 'Processing Meeting...',
      trim: true,
    },

    // Hierarchical map-combine bulleted summary produced by Mistral AI
    summary: {
      type: String,
      default: '',
    },

    // Numbered list of action items with task description, owner, and deadline
    actionItems: {
      type: String,
      default: '',
    },

    // Numbered list of strategic decisions agreed upon during the recording
    keyDecisions: {
      type: String,
      default: '',
    },

    // Numbered list of open questions or topics requiring future follow-up
    openQuestions: {
      type: String,
      default: '',
    },

    // The raw complete speech-to-text transcript generated by Whisper / Sarvam
    transcript: {
      type: String,
      default: '',
    },

    // Embedded array of RAG conversational chat interactions for this meeting
    chatHistory: [ChatMessageSchema],

    // Error message capture if processing fails
    errorMessage: {
      type: String,
      default: null,
    },
  },
  {
    // Automatically manage createdAt and updatedAt timestamps
    timestamps: true,
  }
);

// Create and export the Mongoose model
const Meeting = mongoose.model('Meeting', MeetingSchema);
module.exports = Meeting;
