@app.post("/api/ai/process", response_model=ProcessResponse, tags=["Meeting Processing"])
def process_media(request: ProcessRequest):
    """
    End-to-End Meeting Analysis Pipeline:
      1. Downloads/converts media into 16 kHz mono WAV chunks.
      2. Transcribes speech using Whisper (English) or Sarvam AI (Hinglish).
      3. Generates title and executive bulleted summary using Mistral AI LCEL.
      4. Extracts structured action items, decisions, and open questions.
      5. Builds and persists vector embeddings into ChromaDB for this meeting ID.
    """
    print(f"\n[AI-SERVICE] Received processing request for source: {request.source}")
    print(f"[AI-SERVICE] Language mode: {request.language} | Meeting ID: {request.meeting_id}")

    try:
        # Step 1: Preprocess audio (download YouTube or convert local file to 10-minute WAV chunks)
        chunks = process_input(request.source)

        # Step 2: Transcribe all audio chunks using appropriate STT model
        transcript = transcribe_all(chunks, request.language)

        if not transcript.strip():
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail="Transcription produced an empty result. Check audio quality or URL."
            )

        # Step 3: Extract high-level session title
        title = generate_title(transcript)
        time.sleep(1.2)  # Pacing to respect Mistral 1 RPS rate limit

        # Step 4: Generate map-reduce executive summary
        summary_text = summarize(transcript)
        time.sleep(1.2)

        # Step 5: Extract structured action items (task, owner, deadline)
        action_items = extract_action_items(transcript)
        time.sleep(1.2)

        # Step 6: Extract key decisions agreed upon during the discussion
        key_decisions = extract_key_decisions(transcript)
        time.sleep(1.2)

        # Step 7: Extract open questions and unresolved topics
        open_questions = extract_questions(transcript)

        # Step 8: Build ChromaDB vector store collection isolated by meeting_id
        collection_name = f"meeting_{request.meeting_id}" if request.meeting_id else DEFAULT_COLLECTION_NAME
        build_vector_store(transcript, collection_name=collection_name)

        print(f"[AI-SERVICE] Processing complete for meeting: {request.meeting_id}\n")

        # Return the complete structured intelligence payload
        return ProcessResponse(
            meeting_id=request.meeting_id or "default",
            title=title,
            summary=summary_text,
            action_items=action_items,
            key_decisions=key_decisions,
            open_questions=open_questions,
            transcript=transcript
        )

    except HTTPException:
        # Re-raise explicit HTTP exceptions
        raise
    except Exception as exc:
        # Catch unexpected errors and return descriptive 500 status
        print(f"[AI-SERVICE ERROR] Failed processing media: {exc}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"AI pipeline processing error: {str(exc)}"
        )


@app.post("/api/ai/chat", response_model=ChatResponse, tags=["RAG Question Answering"])
def chat_with_meeting(request: ChatRequest):
    """
    Retrieval-Augmented Generation (RAG) Meeting Chat:
      1. Connects to the ChromaDB vector collection for the designated meeting_id.
      2. Retrieves the top-4 most semantically similar transcript chunks.
      3. Passes the retrieved context and question to Mistral AI with strict anti-hallucination guardrails.
      4. Returns the fact-grounded answer to the client.
    """
    print(f"\n[AI-SERVICE] Received RAG chat query for meeting: {request.meeting_id}")
    print(f"[AI-SERVICE] Question: {request.question}")

    try:
        # Determine the isolated collection name for this meeting
        collection_name = f"meeting_{request.meeting_id}" if request.meeting_id else DEFAULT_COLLECTION_NAME

        # Load the compiled LCEL RAG chain for this collection
        rag_chain = load_rag_chain(collection_name=collection_name)

        # Execute question answering against the grounded context
        answer = ask_question(rag_chain, request.question)

        # Return validated response
        return ChatResponse(
            meeting_id=request.meeting_id or "default",
            question=request.question,
            answer=answer
        )

    except Exception as exc:
        print(f"[AI-SERVICE ERROR] RAG query failed: {exc}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"RAG chat query error: {str(exc)}"
        )


