# =================================================================================

class ProcessRequest(BaseModel):
    """
    Schema for the /api/ai/process endpoint.
    Defines the parameters needed to ingest and analyze a recording.
    """
    # Unique identifier for the meeting generated by MongoDB or the caller
    meeting_id: Optional[str] = Field(
        default="default",
        description="Unique meeting ID used for vector collection isolation."
    )
    # The media location: either a YouTube URL or a local absolute file path
    source: str = Field(
        ...,
        description="YouTube video URL or local media file path (.mp4, .wav, .mp3)."
    )
    # Transcription mode: 'english' (local Whisper) or 'hinglish' (Sarvam AI translation)
    language: str = Field(
        default="english",
        description="Language mode: 'english' or 'hinglish'."
    )


class ProcessResponse(BaseModel):
    """
    Schema representing the complete structured intelligence extracted from the meeting.
    """
    meeting_id: str
    title: str
    summary: str
    action_items: str
    key_decisions: str
    open_questions: str
    transcript: str


class ChatRequest(BaseModel):
    """
    Schema for the /api/ai/chat endpoint.
    Defines the user's question and the target meeting context.
    """
    # The ID of the meeting being queried so ChromaDB retrieves from the correct collection
    meeting_id: Optional[str] = Field(
        default="default",
        description="ID of the meeting to query against in ChromaDB."
    )
    # The user's question about the meeting
    question: str = Field(
        ...,
        description="Natural language question regarding the meeting transcript."
    )


class ChatResponse(BaseModel):
    """
    Schema for RAG chat responses.
    """
    meeting_id: str
    question: str
    answer: str


